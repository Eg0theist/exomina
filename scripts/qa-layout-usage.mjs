// Real renderer with synthetic state. No personal chats, accounts or desktop input.
import { _electron as electron } from 'playwright';
import { createServer } from 'vite';
import path from 'node:path';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
const root = process.cwd(), output = path.resolve(process.argv[2] || '../Workspace/qa-layout-usage');
await mkdir(output, { recursive: true });
const server = await createServer({ root, server: { port: 5184, strictPort: false }, logLevel: 'error' });
await server.listen();
const env = { ...process.env, EXOMINA_DESIGN_QA_URL: `http://localhost:${server.config.server.port}/preview.html`, EXOMINA_DESIGN_QA_DIR: output }; delete env.ELECTRON_RUN_AS_NODE;
const app = await electron.launch({ args: [path.join(root, 'scripts/qa-design-main.cjs')], env, timeout: 30000 });
const report = { passed: false, layout: [], errors: [] };
try {
  const page = await app.firstWindow(); page.setDefaultTimeout(10000);
  page.on('pageerror', error => report.errors.push(error.message));
  await page.getByRole('button', { name: 'Exomina home' }).waitFor();
  await page.locator('[data-chat-id="c1"] .chat-open').click();
  await page.getByLabel('Message', { exact: true }).waitFor();
  for (const width of [960, 1360, 1920, 2560]) {
    await page.setViewportSize({ width, height: 900 });
    await page.waitForFunction(width => window.innerWidth === width, width);
    await page.waitForTimeout(100);
    const rects = await page.evaluate(() => {
      const rect = el => { const r = el.getBoundingClientRect(); return { x: r.x, y: r.y, width: r.width, height: r.height, right: r.right }; };
      return { main: rect(document.querySelector('.main-shell')), scroll: rect(document.querySelector('.chat-scroll')), toolbar: rect(document.querySelector('.composer-toolbar')), buttons: [...document.querySelector('.composer-toolbar').children].filter(el => el.getBoundingClientRect().width > 0).map(el => ({ label: el.getAttribute('aria-label') || el.textContent.trim(), ...rect(el) })) };
    });
    report.layout.push({ width, ...rects });
    assert.ok(Math.abs(rects.scroll.right - rects.main.right) < 2, 'chat scrollbar should sit at the main pane edge');
    const send = rects.buttons.at(-1);
    for (const button of rects.buttons) assert.ok(Math.abs(button.y - send.y) < 4, `all composer buttons share the Send row at ${width}px`);
    assert.ok(send.right <= rects.toolbar.right + 1);
    assert.ok(rects.buttons[0].x >= rects.toolbar.x, 'toolbar must not overflow');
  }
  await page.setViewportSize({ width: 1360, height: 900 });
  await page.getByRole('button', { name: 'Choose AI, model and effort' }).click();
  await page.getByLabel('AI connection', { exact: true }).selectOption('codex');
  await page.getByRole('option', { name: /^GPT-6 4 effort/ }).click();
  await page.getByRole('radio', { name: 'High', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.model-chip').textContent.includes('High'));
  await page.screenshot({ path: path.join(output, 'composer-menu.png') });
  await page.keyboard.press('Escape');
  await page.locator('.chat-scroll').evaluate(el => { el.scrollTop = el.scrollHeight; });
  await page.evaluate(() => {
    window.__exominaPreviewEmit({ type: 'chat.started', conversationId: 'c1', provider: 'codex', startedAt: new Date().toISOString() });
    window.__exominaPreviewEmit({ type: 'chat.activity', conversationId: 'c1', step: { id: 'thinking-live', kind: 'thinking', status: 'running', startedAt: new Date().toISOString(), text: Array.from({ length: 80 }, (_, i) => `Thinking line ${i}: checking the live interface.`).join('\n\n') } });
  });
  const timeline = page.locator('.activity.is-running .activity-steps'); await timeline.waitFor();
  const gap = () => timeline.evaluate(el => el.scrollHeight - el.clientHeight - el.scrollTop);
  await page.waitForFunction(() => { const el = document.querySelector('.activity.is-running .activity-steps'); return el && el.scrollHeight > el.clientHeight && el.scrollHeight - el.clientHeight - el.scrollTop < 2; });
  await page.evaluate(() => window.__exominaPreviewEmit({ type: 'chat.activity', conversationId: 'c1', step: { id: 'thinking-live' }, append: '\n\nNew live line at bottom.' }));
  await page.waitForTimeout(150); assert.ok(await gap() < 2, 'timeline should follow growing thinking text');
  await timeline.evaluate(el => { el.scrollTop = 120; });
  await page.getByRole('button', { name: 'Follow latest activity' }).waitFor();
  await page.locator('.chat-scroll').evaluate(el => { el.scrollTop = el.scrollHeight; });
  const before = await timeline.evaluate(el => el.scrollTop);
  await page.evaluate(() => window.__exominaPreviewEmit({ type: 'chat.activity', conversationId: 'c1', step: { id: 'thinking-live' }, append: '\n\n' + 'Additional live thinking.\n\n'.repeat(20) }));
  await page.waitForTimeout(150);
  assert.ok(Math.abs(await timeline.evaluate(el => el.scrollTop) - before) < 2, 'reading position should survive incoming text');
  await page.screenshot({ path: path.join(output, 'timeline-paused.png') });
  await page.getByRole('button', { name: 'Follow latest activity' }).click();
  assert.ok(await gap() < 2);
  const outer = page.locator('.chat-scroll');
  await outer.evaluate(el => new Promise(resolve => { el.addEventListener('scroll', () => resolve(), { once: true }); el.scrollTop = el.scrollHeight - el.clientHeight - 60; }));
  await page.waitForTimeout(100);
  const outerBefore = await outer.evaluate(el => el.scrollTop);
  const outerRangeBefore = await outer.evaluate(el => el.scrollHeight - el.clientHeight);
  await page.evaluate(() => window.__exominaPreviewEmit({ type: 'chat.activity', conversationId: 'c1', step: { id: 'thinking-live' }, append: '\n\nAnother live thinking line.' }));
  await page.waitForTimeout(150);
  const outerAfter = await outer.evaluate(el => ({ top: el.scrollTop, range: el.scrollHeight - el.clientHeight }));
  assert.ok(Math.abs(outerAfter.top - outerBefore) < 2, `manual reading near the main scrollbar bottom must also stay put: ${JSON.stringify({ before: outerBefore, rangeBefore: outerRangeBefore, after: outerAfter })}`);
  await outer.evaluate(el => { el.scrollTop = el.scrollHeight; });
  await page.locator('.usage-summary').click();
  await page.locator('.usage-details').waitFor();
  await page.screenshot({ path: path.join(output, 'usage-and-composer.png') });
  await page.evaluate(() => window.__exominaPreviewEmit({ type: 'usage', usage: { claude: { provider: 'claude', windows: [{ id: 'five_hour', label: '5-hour session', usedPercent: 12.5, resetsAt: new Date(Date.now() + 600_000).toISOString() }], updatedAt: new Date().toISOString(), fetchStatus: 'error', error: 'Synthetic offline refresh.' } } }));
  await page.getByText('Synthetic offline refresh.', { exact: false }).waitFor();
  await page.getByText('87.5% left · stale', { exact: true }).waitFor();
  await page.keyboard.press('Control+,');
  await page.locator('#settings-appearance').scrollIntoViewIfNeeded();
  await page.getByRole('radiogroup', { name: 'Conversation width' }).getByRole('radio', { name: 'Full width', exact: true }).click();
  await page.getByRole('button', { name: 'Chats', exact: true }).click();
  await page.waitForFunction(() => getComputedStyle(document.documentElement).getPropertyValue('--chat-width').trim() === '100%');
  assert.ok(await page.locator('.messages').evaluate(el => el.getBoundingClientRect().width) > 900, 'Full width should use the available chat pane');
  await page.screenshot({ path: path.join(output, 'full-width.png') });
  assert.deepEqual(report.errors, []);
  report.passed = true;
} finally { await writeFile(path.join(output, 'report.json'), JSON.stringify(report, null, 2)); await app.close(); await server.close(); }
console.log(JSON.stringify(report));
